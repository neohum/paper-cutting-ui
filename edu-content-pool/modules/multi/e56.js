        levels: { easy: '교사가 문장 4장만 읽어 주고 반 전체가 손을 들어 사실·고정관념을 가른다.', base: '문장 6장을 스스로 읽고 두 바구니로 나눈다.', challenge: '나눈 뒤 "그 나라 사람은 다 춤을 잘 춘다"처럼 좋은 내용의 고정관념도 문제인 까닭(한 사람을 한 모습으로 묶음)을 말한다.' },
